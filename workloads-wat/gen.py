# ---------------------------------------------------------------------------
# Extended constant expressions: their only hot path is instantiation, so
# the harness instantiates a fresh instance for every sample of this case
# (Shape::InstantiateEach). 2048 i32 and 512 i64 globals are initialised by
# i32/i64 add/sub/mul trees, and 256 active data segments land at offsets
# computed the same way. The exported function folds every global and a
# word of every segment into the checksum, so a wrong evaluation is a wrong
# result. The `.mvp` twin is the same module with every initializer and
# offset pre-folded to a single const: instantiate-and-call cost without
# extended-const evaluation.
# ---------------------------------------------------------------------------
M32 = 0xFFFFFFFF
M64 = 0xFFFFFFFFFFFFFFFF


def _s32(v):
    v &= M32
    return v - (1 << 32) if v >> 31 else v


def _s64(v):
    v &= M64
    return v - (1 << 64) if v >> 63 else v


def extconst_init():
    rng = random.Random(20260922)

    def tree(t, depth):
        mask = M32 if t == "i32" else M64
        if depth == 0:
            c = rng.randrange(1 << 16)
            return f"({t}.const {c})", c
        op = rng.choice(["add", "sub", "mul"])
        a, av = tree(t, depth - 1)
        b, bv = tree(t, depth - 1)
        v = {"add": av + bv, "sub": av - bv, "mul": av * bv}[op] & mask
        return f"({t}.{op} {a} {b})", v

    g32 = [tree("i32", 3) for _ in range(2048)]   # 7 ops + 8 consts each
    g64 = [tree("i64", 3) for _ in range(512)]
    segs = []
    for k in range(256):
        # offset = k * 16 + 4096, spelled as an extended-const tree
        a = rng.randrange(1, 64)
        e = f"(i32.add (i32.mul (i32.const {k}) (i32.const 16)) (i32.sub (i32.const {4096 + a}) (i32.const {a})))"
        segs.append((e, k * 16 + 4096, rng.randrange(1 << 32)))

    def module(extended):
        out = ["  (memory 1)"]
        for i, (e, v) in enumerate(g32):
            out.append(f"  (global $a{i} i32 {e if extended else f'(i32.const {_s32(v)})'})")
        for i, (e, v) in enumerate(g64):
            out.append(f"  (global $b{i} i64 {e if extended else f'(i64.const {_s64(v)})'})")
        for e, off, word in segs:
            data = "".join(f"\\{(word >> (8 * j)) & 0xFF:02x}" for j in range(4))
            out.append(f"  (data {f'(offset {e})' if extended else f'(i32.const {off})'} \"{data}\")")
        body = ["    (local $h i32) (local $w i64)", "    (local.set $h (local.get $seed))"]
        for i in range(len(g32)):
            body.append(f"    (local.set $h (i32.add (i32.rotl (local.get $h) (i32.const 3)) (global.get $a{i})))")
        for i in range(len(g64)):
            body.append(f"    (local.set $w (i64.add (i64.rotl (local.get $w) (i64.const 5)) (global.get $b{i})))")
        for _, off, _ in segs:
            body.append(f"    (local.set $h (i32.xor (i32.rotl (local.get $h) (i32.const 1)) (i32.load (i32.const {off}))))")
        body.append("    (i32.add (local.get $h) (i32.wrap_i64 (i64.xor (local.get $w) (i64.shr_u (local.get $w) (i64.const 32)))))")
        out.append("  (func (export \"extconst_init\") (param $seed i32) (result i32)\n" + "\n".join(body) + ")")
        return "\n".join(out)

    write("extconst_init", f""";; Extended constant expressions (generated by gen.py): 2048 i32 + 512 i64
;; globals and 256 data-segment offsets computed by add/sub/mul trees.
;; Timed per sample as instantiate + one call.
(module
{module(True)})
""")
    write("extconst_init.mvp", f""";; MVP twin of extconst_init (generated by gen.py): identical module with
;; every initializer and segment offset pre-folded to one const.
(module
{module(False)})
""")


