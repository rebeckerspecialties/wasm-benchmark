#!/usr/bin/env python3
"""Generate crates/benchmark-core/src/score_reference.rs, the app's score
reference times, from an iPhone pass's per-rep matrix CSV.

For every case still in the case table, the reference is the geometric
mean, over the engines that ran the case in at least half of the reps, of
each engine's per-call median (the median of its per-rep medians). A
benchmark score is then 100 x reference / measured median: the typical
engine on the reference device scores 100 on every benchmark, and higher
is faster.

Usage:
  scripts/score-reference.py [matrix.csv] [out.rs]
Defaults: docs/runtime-comparison-2026-09-22/iphonexs-matrix.csv and
crates/benchmark-core/src/score_reference.rs.
"""

import csv
import math
import os
import re
import statistics
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    ROOT, "docs/runtime-comparison-2026-09-22/iphonexs-matrix.csv")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    ROOT, "crates/benchmark-core/src/score_reference.rs")

# Case ids from the CASES table (`c("id", ...)` or `Case { id: "id", ... }`).
cases_rs = open(os.path.join(ROOT, "crates/benchmark-core/src/cases.rs")).read()
table = cases_rs[cases_rs.index("pub const CASES"):]
CASES = set(re.findall(r'(?:c\(\s*|id:\s*)"([^"]+)"', table[:table.index("];")]))

rows = [r for r in csv.DictReader(open(SRC)) if r["case"] in CASES]
reps = defaultdict(set)      # case -> reps seen
ok = defaultdict(list)       # (case, runtime) -> per-rep medians
order = []
for r in rows:
    case = r["case"]
    if case not in order:
        order.append(case)
    reps[case].add(r["rep"])
    if r["ok"] == "True" and r["median_ns"]:
        ok[(case, r["runtime"])].append(float(r["median_ns"]))

entries = []
for case in order:
    need = len(reps[case]) / 2
    medians = [statistics.median(v) for (c, _), v in ok.items() if c == case and len(v) >= need]
    if not medians:
        continue
    ref = math.exp(sum(math.log(m) for m in medians) / len(medians))
    entries.append((case, round(ref), len(medians)))

rel = os.path.relpath(SRC, ROOT)
with open(OUT, "w") as f:
    f.write(f"""//! Score reference times, generated by scripts/score-reference.py from
//! {rel}. Do not edit.
//!
//! Each case's reference is the geometric mean, over the engines that ran
//! it, of the engines' per-call medians on the iPhone XS Max (A12 E-cores).
//! A benchmark's score is 100 x reference / measured median, so the
//! typical engine on that phone scores 100.

/// (case id, reference nanoseconds per call, engines in the mean)
pub const SCORE_REFERENCE_NS: &[(&str, u64, u32)] = &[
""")
    for case, ref, n in sorted(entries):
        f.write(f"    ({case!r}, {ref}, {n}),\n".replace("'", '"'))
    f.write("];\n")
print(f"wrote {len(entries)} references to {os.path.relpath(OUT, ROOT)}")
